#!/usr/bin/env python3
"""
Generates shim/hv_stubs.inc: an interposed stub for every x86 Hypervisor.framework function that returns hv_return_t
and is not implemented by the shim, answering HV_UNSUPPORTED instead of letting the call fall through to Apple's
implementation (which cannot work on an AMD CPU).

    ./scripts/gen-hv-stubs.py > shim/hv_stubs.inc

The prototypes come from the SDK header through the preprocessor, so the stubs always match your SDK.
"""
import re, subprocess, sys, tempfile, os

IMPLEMENTED = {
    'hv_vm_create', 'hv_vm_destroy', 'hv_vm_map', 'hv_vm_unmap', 'hv_vm_protect', 'hv_vm_sync_tsc',
    'hv_vcpu_create', 'hv_vcpu_destroy', 'hv_vcpu_run', 'hv_vcpu_run_until', 'hv_vcpu_interrupt',
    'hv_vcpu_read_register', 'hv_vcpu_write_register', 'hv_vcpu_read_fpstate', 'hv_vcpu_write_fpstate',
    'hv_vcpu_read_msr', 'hv_vcpu_write_msr', 'hv_vcpu_enable_native_msr', 'hv_vcpu_enable_managed_msr',
    'hv_vcpu_flush', 'hv_vcpu_invalidate_tlb', 'hv_vcpu_get_exec_time',
    'hv_vmx_vcpu_read_vmcs', 'hv_vmx_vcpu_write_vmcs', 'hv_vmx_read_capability',
    'hv_vcpu_set_tsc_relative', 'hv_vcpu_set_msr_access', 'hv_vmx_get_msr_info',
    'hv_vmx_vcpu_set_apic_address', 'hv_vmx_vcpu_set_apic_address_space',
}

with tempfile.TemporaryDirectory() as d:
    src = os.path.join(d, 't.c')
    open(src, 'w').write('#include <Hypervisor/Hypervisor.h>\n')
    pre = subprocess.check_output(['cc', '-arch', 'x86_64', '-E', '-P', src], text=True)

pre = re.sub(r'__attribute__\(\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)\)', '', pre)   # strip attributes (nested parens)
pre = re.sub(r'\s+', ' ', pre)

out = []
for m in re.finditer(r'(?:extern\s+)?hv_return_t\s+(hv_[a-z0-9_]+)\s*\(([^;{}]*?)\)\s*;', pre):
    name, args = m.group(1), m.group(2).strip()
    if name in IMPLEMENTED:
        continue
    out.append((name, args))

seen = set()
print('// Generated by scripts/gen-hv-stubs.py from the Hypervisor.framework SDK header. Do not edit.')
print('// Every x86 hv_* function the shim does not implement answers HV_UNSUPPORTED.')
for name, args in sorted(out):
    if name in seen:
        continue
    seen.add(name)
    print(f'RHV_STUB({name}, ({args}))')
