#!/usr/bin/env python3
"""
Regenerates kext/Source/VmcsFields.def from the Hypervisor.framework SDK header.

The .def lists every VMCS field the framework exposes (name, encoding), sorted by encoding, so the
kext can keep a shadow value for each one and the host tests can check our table against Apple's
constants. Run it again after an SDK update:

    ./scripts/gen-vmcs-fields.py > kext/Source/VmcsFields.def
"""
import re, subprocess, sys

sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
hdr = open(f'{sdk}/System/Library/Frameworks/Hypervisor.framework/Headers/hv_arch_vmx.h').read()

fields = {}
for m in re.finditer(r'^\s+(VMCS_[A-Z0-9_]+)\s*=\s*(0x[0-9a-fA-F]+)\s*,?', hdr, re.M):
    name, enc = m.group(1), int(m.group(2), 16)
    if name in ('VMCS_MAX',):
        continue
    fields[name] = enc

# VMCS_HOST_RSP is defined through a macro in the header.
fields.setdefault('VMCS_HOST_RSP', int(re.search(r'__VMCS_HOST_RSP\s+(0x[0-9a-fA-F]+)', hdr).group(1), 16))

by_enc = {}
for name, enc in fields.items():
    by_enc.setdefault(enc, name)          # aliases (VMCS_GUEST_IGNORE_IRQ) are not listed twice

print('// Generated by scripts/gen-vmcs-fields.py from the Hypervisor.framework SDK header. Do not edit.')
print('// F(name, encoding), sorted by encoding.')
for enc in sorted(by_enc):
    print(f'F({by_enc[enc]}, 0x{enc:08x})')
